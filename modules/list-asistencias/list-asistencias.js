function formatoNombreCompleto(value, row) {
    var id = row.trabajador_id || row.id;
    var nombreCompleto = (row.nombre || '') + ' ' + (row.apellidos || '');
    if (value && !nombreCompleto.trim()) { nombreCompleto = value; } // fallback if value is passed but fields depend on row

    // Si value ya es el nombre completo (caso de list-trabajadores donde quizas value viene lleno)
    if (!row.nombre && !row.apellidos && value) {
        nombreCompleto = value;
    }

    if (id) {
        return '<a href="index.php?module=ficha-trabajador&id=' + id + '" style="cursor: pointer; color: inherit; text-decoration: none;" onmouseover="this.style.textDecoration=\'underline\'; this.style.color=\'#337ab7\';" onmouseout="this.style.textDecoration=\'none\'; this.style.color=\'inherit\';">' + nombreCompleto + '</a>';
    }
    return nombreCompleto;
}

// Formatter for photo in Trabajadores Presentes table
function formatoFotoPresente(value, row) {
    if (row.foto) {
        return '<img src="data:image/jpeg;base64,' + row.foto + '" style="width: 50px; height: 50px; border-radius: 50%; object-fit: cover;" />';
    } else {
        return '<div style="width: 50px; height: 50px; border-radius: 50%; background-color: #ddd; display: flex; align-items: center; justify-content: center;"><i class="fa fa-user" style="font-size: 24px; color: #999;"></i></div>';
    }
}

// Formatter for photo in main attendance tables
function formatoFoto(value, row) {
    // Si hay una foto guardada, mostrarla
    if (value) {
        // Si es una data URL (base64), usarla directamente
        if (value.startsWith('data:')) {
            return '<img src="' + value + '" style="width: 50px; height: 50px; object-fit: cover; border-radius: 4px;" class="img-thumbnail" alt="Foto del trabajador">';
        }
        // Si la ruta ya es una URL completa, usarla directamente
        if (value.startsWith('http') || value.startsWith('/')) {
            return '<img src="' + value + '" style="width: 50px; height: 50px; object-fit: cover; border-radius: 4px;" class="img-thumbnail" alt="Foto del trabajador">';
        }
        // Si no, asumir que es solo el nombre del archivo
        var basePath = 'uploads/fotos_trabajadores/';
        return '<img src="' + basePath + value + '" style="width: 50px; height: 50px; object-fit: cover; border-radius: 4px;" class="img-thumbnail" alt="Foto del trabajador">';
    }

    // Si no hay foto, mostrar un avatar por defecto
    return '<div style="width: 50px; height: 50px; background-color: #f0f0f0; display: flex; align-items: center; justify-content: center; border-radius: 4px;" class="img-thumbnail">' +
        '<i class="fa fa-user" style="font-size: 24px; color: #999;"></i>' +
        '</div>';
}

// Formateador para la columna de ausencia
function formatoAusencia(value, row) {
    if (row.ausencia == 3) {
        return '<span class="label label-primary">VACACIONES</span><br>';
    }
    else if (row.ausencia == 1) {
        let tooltip = '';
        if (row.justificacion) {
            tooltip = ` data-toggle="tooltip" data-placement="top" title="${row.justificacion}"`;
        }
        
        // Botón de justificar
        var rowData = encodeURIComponent(JSON.stringify(row));
        var btnJustificar = '<button class="btn btn-icon btn-xs btn-info fa fa-pencil" title="Justificar" style="margin-left: 5px; padding: 1px 4px; font-size: 10px;" onclick="editarAsistenciaEncoded(\'' + rowData + '\'); return false;"></button>';

        return `<span class="label label-danger"${tooltip}>AUSENTE</span>${btnJustificar}<br><small>${row.tipo_ausencia || ''}</small>`;
    }
    else if (row.tipo_horario != 1 && row.tipo_horario != null) {
        return '<span class="label label-warning">ESPECIAL</span>';
    }
    else if (row.tardanza == 1) {
        let tooltip = '';
        if (row.justificacion) {
            tooltip = ` data-toggle="tooltip" data-placement="top" title="${row.justificacion}"`;
        }
        
        // Botón de justificar
        var rowData = encodeURIComponent(JSON.stringify(row));
        var btnJustificar = '<button class="btn btn-icon btn-xs btn-info fa fa-pencil" title="Justificar" style="margin-left: 5px; padding: 1px 4px; font-size: 10px;" onclick="editarAsistenciaEncoded(\'' + rowData + '\'); return false;"></button>';

        return `<span class="label label-success"${tooltip}>PRESENTE</span>${btnJustificar}<br><small>Tardanza</small>`;
    }
    else {
        return '<span class="label label-success">PRESENTE</span>';
    }
}

